"""Core data models for questions, note chunks, topic weights, and session state."""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
from typing import Literal


QuestionStatus = Literal["pending", "completed"]


@dataclass
class Question:
    """Represents a single parsed question from the question bank."""

    id: str
    text: str
    marks: int
    topic: str = "General"
    status: QuestionStatus = "pending"

    def to_dict(self) -> dict:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: dict) -> "Question":
        return cls(
            id=str(data["id"]),
            text=str(data["text"]),
            marks=int(data["marks"]),
            topic=str(data.get("topic", "General")),
            status=data.get("status", "pending"),
        )


@dataclass(frozen=True)
class NoteChunk:
    """A chunk of study material with source metadata for grounded citations."""

    chunk_id: str
    source: str
    text: str


@dataclass
class TopicImportance:
    """Aggregated importance score for a lesson topic."""

    topic: str
    question_count: int
    total_marks: int
    priority: Literal["High", "Medium", "Low"]
    rationale: str = ""

    def to_dict(self) -> dict:
        return asdict(self)


@dataclass
class SolvedAnswer:
    """A single grounded answer generated by the solver loop."""

    question_id: str
    marks: int
    question_text: str
    answer_markdown: str
    citations: list[str] = field(default_factory=list)

    def to_dict(self) -> dict:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: dict) -> "SolvedAnswer":
        return cls(
            question_id=str(data["question_id"]),
            marks=int(data["marks"]),
            question_text=str(data["question_text"]),
            answer_markdown=str(data["answer_markdown"]),
            citations=list(data.get("citations", [])),
        )


@dataclass
class SessionState:
    """Persistent checkpoint state for an autonomous solving run."""

    session_id: str
    style_instructions: str
    questions: list[Question] = field(default_factory=list)
    important_topics: list[TopicImportance] = field(default_factory=list)
    answers: list[SolvedAnswer] = field(default_factory=list)
    batch_count: int = 0

    def pending_by_marks(self, marks: int) -> list[Question]:
        """Return all pending questions matching a given mark weight."""
        return [q for q in self.questions if q.status == "pending" and q.marks == marks]

    def has_pending(self) -> bool:
        """Return True if any question remains unsolved."""
        return any(q.status == "pending" for q in self.questions)

    def to_dict(self) -> dict:
        return {
            "session_id": self.session_id,
            "style_instructions": self.style_instructions,
            "questions": [q.to_dict() for q in self.questions],
            "important_topics": [t.to_dict() for t in self.important_topics],
            "answers": [a.to_dict() for a in self.answers],
            "batch_count": self.batch_count,
        }

    @classmethod
    def from_dict(cls, data: dict) -> "SessionState":
        return cls(
            session_id=str(data["session_id"]),
            style_instructions=str(data.get("style_instructions", "")),
            questions=[Question.from_dict(q) for q in data.get("questions", [])],
            important_topics=[TopicImportance(**t) for t in data.get("important_topics", [])],
            answers=[SolvedAnswer.from_dict(a) for a in data.get("answers", [])],
            batch_count=int(data.get("batch_count", 0)),
        )
